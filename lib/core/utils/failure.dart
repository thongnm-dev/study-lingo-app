import 'package:equatable/equatable.dart';

/// Functional error type returned from repositories/use cases as the Left of
/// `Either<Failure, T>` (dartz). Lets the presentation layer pattern-match on
/// failure flavors without leaking exception types up from the data layer.
abstract class Failure extends Equatable {
  final String message;

  const Failure(this.message);

  @override
  List<Object?> get props => [message];
}

class ServerFailure extends Failure {
  const ServerFailure(super.message);
}

class NetworkFailure extends Failure {
  const NetworkFailure(super.message);
}

class CacheFailure extends Failure {
  const CacheFailure(super.message);
}

class ValidationFailure extends Failure {
  const ValidationFailure(super.message);
}

class UnknownFailure extends Failure {
  const UnknownFailure(super.message);
}
